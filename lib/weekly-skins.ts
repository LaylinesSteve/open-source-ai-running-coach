export const SKIN_PREVIEW_STORAGE_KEY = 'weekly-skin-preview';

export function getSkin(id: SkinId): Skin {
  return SKINS.find((s) => s.id === id) ?? SKINS[0];
}

export function controlStyle(skinId: SkinId, index: number): CSSProperties {
  const cfg = CONTROLS[skinId];
  if (cfg.clips) {
    return { clipPath: cfg.clips[index % cfg.clips.length], borderRadius: 0 };
  }
  return { borderRadius: cfg.radius };
}

